create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  match_id text not null,
  match_name text not null,
  date text not null,
  venue text not null,
  stand text not null,
  tickets integer not null check (tickets > 0),
  total numeric not null check (total >= 0),
  customer_name text,
  customer_email text,
  booked_at timestamptz not null default now()
);

alter table public.bookings add column if not exists customer_name text;
alter table public.bookings add column if not exists customer_email text;

alter table public.bookings enable row level security;

drop policy if exists "Allow public booking reads" on public.bookings;
create policy "Allow public booking reads"
  on public.bookings for select
  to anon
  using (true);

drop policy if exists "Allow public booking inserts" on public.bookings;
create policy "Allow public booking inserts"
  on public.bookings for insert
  to anon
  with check (true);

notify pgrst, 'reload schema';
